export async function POST(req: Request) {
  try {
    const apiKey = process.env.OPENAI_API_KEY;

    if (!apiKey) {
      return NextResponse.json(
        { error: "Не подключён OPENAI_API_KEY в Vercel." },
        { status: 503 }
      );
    }

    const supabase = await createClient();
    const {
      data: { user },
      error: authError,
    } = await supabase.auth.getUser();

    if (authError || !user) {
      return NextResponse.json(
        { error: "Войди в аккаунт, чтобы создавать материалы." },
        { status: 401 }
      );
    }

    const body = await req.json();

    const {
      type,
      topic,
      age = "4 года",
      language = "both",
      format = "Цветной, для детей"
    } = body;

    if (
      !prompts[type] ||
      typeof topic !== "string" ||
      !topic.trim()
    ) {
      return NextResponse.json(
        { error: "Проверь тип материала и тему." },
        { status: 400 }
      );
    }

    if (topic.length > 300) {
      return NextResponse.json(
        { error: "Слишком длинная тема. Сократи её." },
        { status: 400 }
      );
    }

    const { data: quotaData, error: quotaError } =
      await supabase.rpc("consume_generation");

    if (quotaError) {
      console.error("QUOTA ERROR:", quotaError);

      return NextResponse.json(
        { error: "Ошибка проверки дневного лимита генераций. Проверь Supabase." },
        { status: 500 }
      );
    }

    const quota = Array.isArray(quotaData)
      ? quotaData[0]
      : quotaData;

    if (!quota?.allowed) {
      return NextResponse.json(
        {
          error: "Ты использовала все 20 генераций на сегодня. Завтра лимит обновится, и ты снова сможешь создавать материалы бесплатно."
        },
        { status: 429 }
      );
    }

    let languageRule = "";

    if (language === "ru") {
      languageRule = "Пиши только на грамотном русском языке. Весь материал должен быть на русском.";
    } else if (language === "kz") {
      languageRule = "Қазақ тілінде сауатты жаз. Барлық материал тек қазақ тілінде болуы керек.";
    } else {
      languageRule =
        "Сначала создай полноценную версию на русском языке, затем отдельную полноценную версию на грамотном казахском языке. Не смешивай языки. Сохрани одинаковую структуру обеих версий.";
    }

    const openai = new OpenAI({ apiKey });

    const response = await openai.chat.completions.create({
      model: process.env.OPENAI_MODEL || "gpt-4.1-mini",
      messages: [
        {
          role: "system",
          content: `
Ты — профессиональный методист дошкольного образования
и автор оригинальных образовательных материалов.

Создавай качественные, интересные, безопасные
и соответствующие возрасту разработки.

Учитывай возраст детей и реальные условия детского сада.

Для дидактических игр обязательно создавай
понятную и полноценную игровую механику.
Разнообразь способы взаимодействия детей с материалами.
Не используй один и тот же шаблон игры для разных тем.

Каждая игра должна быть практически применима:
педагог должен суметь подготовить её по твоему описанию.

Не используй формулировки, подразумевающие,
что ребёнок полностью освоил навык за одно занятие.

Используй формулировки процесса:
учится, пробует, закрепляет, дағдыланады.

Соблюдай структуру и все требования задания.
Не пропускай разделы.
          `
        },
        {
          role: "user",
          content: `
${prompts[type]}

ТЕМА: ${topic}
ВОЗРАСТ: ${age}
ОФОРМЛЕНИЕ: ${format}

${languageRule}

Подготовь подробный, структурированный
и готовый к использованию материал.

Учитывай реальные условия работы детского сада.
          `
        }
      ],
      temperature: 0.9
    });

    const content =
      response.choices[0]?.message?.content;

    if (!content) {
      throw new Error("OpenAI вернул пустой ответ.");
    }

    return NextResponse.json({
      success: true,
      content,
      remaining: quota.remaining
    });

  } catch (e: unknown) {
    console.error("AI KIDS GENERATION ERROR:", e);

    const error = e as {
      message?: string;
      status?: number;
    };

    if (error.status === 401) {
      return NextResponse.json(
        { error: "OpenAI не принял API-ключ. Проверь OPENAI_API_KEY." },
        { status: 502 }
      );
    }

    if (error.status === 429) {
      return NextResponse.json(
        { error: "Превышен лимит запросов OpenAI или недостаточно средств на API-балансе." },
        { status: 429 }
      );
    }

    if (error.status === 404) {
      return NextResponse.json(
        { error: "Модель OpenAI не найдена. Проверь OPENAI_MODEL." },
        { status: 502 }
      );
    }

    return NextResponse.json(
      {
        error: "Ошибка генерации: " +
          (error.message || "Неизвестная ошибка сервера.")
      },
      { status: 500 }
    );
  }
}
