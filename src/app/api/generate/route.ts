
import OpenAI from "openai";
import { NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";

export const runtime = "nodejs";
export const maxDuration = 120;

const prompts: Record<string, string> = {
  game: `Создай оригинальную дидактическую игру для дошкольников. Включи название, цель, задачи, возраст, материалы, подготовку, правила, подробный ход игры с репликами воспитателя, три уровня сложности, вопросы, варианты игры и индивидуальную работу. Используй разнообразные игровые механики.`,

  story: `Напиши оригинальную добрую сказку для дошкольников. Добавь короткие эпизоды, понятный сюжет, повторяющиеся фразы, вопросы и творческое задание.`,

  illustration: `Подготовь подробное техническое задание для детской иллюстрации: композиция, персонажи, палитра, фон, стиль и требования к печати.`,

  cards: `Разработай набор карточек для печати. Укажи количество, содержание, подписи, правила использования и размещение на листе А4.`,

  worksheet: `Создай рабочий лист для дошкольника на одну страницу А4, вертикально.

Тема: указанная пользователем.
Возраст: указанный пользователем.

Создай пять коротких упражнений:
1. Посчитать предметы и записать число.
2. Соединить животных с детёнышами.
3. Найти лишний предмет.
4. Обвести всех, кто умеет летать.
5. Пройти простой лабиринт от щенка к маме-собаке.

Внизу добавь «Моё настроение» с тремя смайликами.

ВАЖНО:
- Пиши короткие, понятные инструкции.
- Не используй заглушки вместо изображений.
- Не пиши «(рисунок котика)» или «(лабиринт)».
- Не включай ответы в детскую часть.
- Оставляй место для ответов ребёнка.
- Для задания №4 используй только условие «Обведи тех, кто умеет летать».
- В задании №4 правильные объекты должны быть действительно способными летать.
- После детской части добавь маркер ===TEACHER_GUIDE=== и ответы воспитателю.`,

  lesson: `Подготовь краткосрочный план занятия на 25 минут: тема, цель, задачи, материалы, этапы с примерным временем, речь воспитателя, задания и рефлексия.`,

  author: `Разработай авторскую методическую идею: актуальность, цель, задачи, новизна, целевая группа, материалы, этапы, примеры заданий и рекомендации.`
};

export async function POST(req: Request) {
  try {
    const apiKey = process.env.OPENAI_API_KEY;

    if (!apiKey) {
      return NextResponse.json(
        { error: "Не подключён OPENAI_API_KEY в Vercel." },
        { status: 503 }
      );
    }

    const supabase = await createClient();

    const {
      data: { user },
      error: authError,
    } = await supabase.auth.getUser();

    if (authError || !user) {
      return NextResponse.json(
        { error: "Войди в аккаунт, чтобы создавать материалы." },
        { status: 401 }
      );
    }

    const body = await req.json();

    const {
      type,
      topic,
      age = "4 года",
      language = "both",
      format = "Цветной, для детей"
    } = body;

    if (
      !prompts[type] ||
      typeof topic !== "string" ||
      !topic.trim()
    ) {
      return NextResponse.json(
        { error: "Проверь тип материала и тему." },
        { status: 400 }
      );
    }

    if (topic.length > 300) {
      return NextResponse.json(
        { error: "Слишком длинная тема. Сократи её." },
        { status: 400 }
      );
    }

    const { data: quotaData, error: quotaError } =
      await supabase.rpc("consume_generation");

    if (quotaError) {
      console.error("QUOTA ERROR:", quotaError);

      return NextResponse.json(
        { error: "Ошибка проверки дневного лимита генераций." },
        { status: 500 }
      );
    }

    const quota = Array.isArray(quotaData)
      ? quotaData[0]
      : quotaData;

    if (!quota?.allowed) {
      return NextResponse.json(
        {
          error: "Ты использовала все 20 генераций на сегодня. Завтра лимит обновится."
        },
        { status: 429 }
      );
    }

    let languageRule = "";

    if (language === "ru") {
      languageRule = "Пиши только на грамотном русском языке.";
    } else if (language === "kz") {
      languageRule = "Пиши только на грамотном казахском языке.";
    } else {
      languageRule =
        "Создай полноценную версию на русском языке, затем отдельную версию на казахском. Не смешивай языки.";
    }

    const openai = new OpenAI({ apiKey });
    const isWorksheet = type === "worksheet";

    const response = await openai.chat.completions.create({
      model: process.env.OPENAI_MODEL || "gpt-4.1-mini",
      messages: [
        {
          role: "system",
          content: isWorksheet
            ? `Ты профессиональный методист дошкольного образования и автор рабочих листов. Создавай конкретные, понятные задания для детей. Не используй текстовые заглушки вместо изображений. Ответы воспитателю отделяй маркером ===TEACHER_GUIDE===. Для задания «Обведи тех, кто умеет летать» правильными ответами могут быть птицы, бабочки и пчёлы. Не указывай животных, которые не умеют летать. Проверяй соответствие ответов воспитателя условиям заданий. Используй процессные формулировки: учится, пробует, закрепляет, дағдыланады.`
            : `Ты профессиональный методист дошкольного образования. Создавай качественные, интересные и безопасные материалы с учётом возраста детей. Используй процессные формулировки: учится, пробует, закрепляет, дағдыланады.`
        },
        {
          role: "user",
          content: `
${prompts[type]}

ТЕМА: ${topic}
ВОЗРАСТ: ${age}
ОФОРМЛЕНИЕ: ${format}

${languageRule}

Подготовь конкретный, структурированный и готовый к использованию материал.
          `
        }
      ],
      temperature: isWorksheet ? 0.5 : 0.9
    });

    const fullContent = response.choices[0]?.message?.content;

    if (!fullContent) {
      throw new Error("OpenAI вернул пустой ответ.");
    }

    let content = fullContent;
    let teacherGuide = "";

    if (isWorksheet) {
      const marker = "===TEACHER_GUIDE===";
      const markerIndex = fullContent.indexOf(marker);

      if (markerIndex !== -1) {
        content = fullContent.slice(0, markerIndex).trim();
        teacherGuide = fullContent
          .slice(markerIndex + marker.length)
          .trim();
      }
    }

    let illustration: string | null = null;

    if (isWorksheet) {
      const isBlackWhite = format.toLowerCase().includes("чёрно-бел");
      const isPastel = format.toLowerCase().includes("пастель");

      const visualStyle = isBlackWhite
        ? `Чёрно-белая детская раскраска. Чёткие толстые контуры, белый фон, никаких серых заливок.`
        : isPastel
          ? `Мягкие пастельные цвета, красивые объёмные персонажи, нежное освещение.`
          : `Профессиональный милый 3D Cartoon Kids. Объёмные мультяшные животные, выразительные добрые лица, яркие гармоничные цвета, мягкие тени, качественная детская 3D-графика.`;

      const imagePrompt = `
СОЗДАЙ ПОЛНОЦЕННУЮ ВИЗУАЛЬНУЮ СТРАНИЦУ РАБОЧЕГО ЛИСТА ДЛЯ ДЕТЕЙ.

ФОРМАТ:
Вертикальный А4, соотношение сторон примерно 2:3.
Высокое качество, пригодное для печати.
Белый или очень светлый фон.
${visualStyle}

ТЕМА: ${topic}
ВОЗРАСТ: ${age}

ГЛАВНАЯ ЦЕЛЬ:
Ребёнок должен понять, ЧТО ДЕЛАТЬ, ГЛЯДЯ НА РИСУНКИ.
Нарисуй пять настоящих визуальных упражнений, а не просто красивую картинку с животными.

РАЗДЕЛ 1 — ПОСЧИТАЙ:
Нарисуй отдельные группы предметов.
В каждой группе соблюдай указанное в задании точное количество объектов.
Рядом с каждой группой нарисуй пустую клетку для записи ответа.
Изображения должны быть крупными и хорошо различимыми.

РАЗДЕЛ 2 — СОЕДИНИ ПАРЫ:
Нарисуй две отдельные вертикальные колонки.
Слева — взрослые животные.
Справа — соответствующие детёныши.
Между колонками оставь свободное пространство для проведения линий.
Не соединяй пары заранее.

РАЗДЕЛ 3 — НАЙДИ ЛИШНЕЕ:
Нарисуй в одном ряду несколько предметов одной группы и один явно лишний предмет.
Оставь свободное место вокруг каждого предмета, чтобы ребёнок мог обвести ответ.
Не обводи правильный ответ заранее.

РАЗДЕЛ 4 — ОБВЕДИ ТЕХ, КТО УМЕЕТ ЛЕТАТЬ:
Это задание обязательно должно быть именно на умение летать.
Нарисуй несколько разных существ: например, воробья, бабочку, пчелу, корову и лягушку.
Среди них должны быть летающие и нелетающие.
Птица, бабочка и пчела должны быть хорошо различимы.
Оставь свободное место вокруг каждого изображения, чтобы ребёнок мог обвести подходящие объекты.
Не обводи правильные ответы заранее.
Не используй условие про хвосты, лапы или другие признаки.

РАЗДЕЛ 5 — ЛАБИРИНТ:
Нарисуй настоящий простой лабиринт с непрерывными стенками и одним правильным проходом.
В начале поставь милого щенка.
В конце поставь его маму-собаку.
Путь должен быть доступным для ребёнка 4 лет.
Оставь дорожку, по которой можно провести карандашом.

ОБЩАЯ КОМПОЗИЦИЯ:
Пять крупных, хорошо отделённых друг от друга блоков сверху вниз.
Каждый блок должен наглядно показывать действие, которое нужно выполнить.
Оставляй пустые поля для записи, соединения и обведения.
Не перегружай страницу мелкими деталями.

ОЧЕНЬ ВАЖНО:
- Не рисуй случайную композицию из животных.
- Не объединяй все объекты в одну общую сцену.
- Не рисуй ответы и готовые линии соединения.
- Не добавляй нечитаемые буквы, случайные цифры и псевдотекст.
- Не добавляй водяные знаки и логотипы.
- Каждый раздел должен выглядеть как реальное задание в рабочей тетради.

ПЯТЬ ЗАДАНИЙ И ИХ СОДЕРЖАНИЕ:
${content}

Используй содержание заданий выше как инструкцию для объектов на странице.
Сохраняй условие задания №4: обвести тех, кто умеет летать.
      `;

      const imageResponse = await openai.images.generate({
        model: process.env.OPENAI_IMAGE_MODEL || "gpt-image-2.5-flare",
        size: "1024x1536",
        quality: "medium",
        n: 1,
        output_format: "png",
        background: "opaque",
        prompt: imagePrompt
      });

      const imageBase64 = imageResponse.data?.[0]?.b64_json;

      if (!imageBase64) {
        throw new Error("Не удалось получить иллюстрации для рабочего листа.");
      }

      illustration = `data:image/png;base64,${imageBase64}`;
    }

    return NextResponse.json({
      success: true,
      content,
      teacherGuide,
      illustration,
      remaining: quota.remaining
    });

  } catch (e: unknown) {
    console.error("AI KIDS GENERATION ERROR:", e);

    const error = e as {
      message?: string;
      status?: number;
    };

    if (error.status === 401) {
      return NextResponse.json(
        { error: "OpenAI не принял API-ключ. Проверь OPENAI_API_KEY." },
        { status: 502 }
      );
    }

    if (error.status === 429) {
      return NextResponse.json(
        { error: "Превышен лимит OpenAI или недостаточно средств на API-балансе." },
        { status: 429 }
      );
    }

    if (error.status === 404) {
      return NextResponse.json(
        { error: "Модель OpenAI не найдена. Проверь настройки модели." },
        { status: 502 }
      );
    }

    return NextResponse.json(
      {
        error: "Ошибка генерации: " +
          (error.message || "Неизвестная ошибка сервера.")
      },
      { status: 500 }
    );
  }
}
